-- Tablas
CREATE TABLE [__EFMigrationsHistory] (
    [MigrationId] nvarchar(150) NOT NULL,
    [ProductVersion] nvarchar(32) NOT NULL,
    CONSTRAINT [PK___EFMigrationsHistory] PRIMARY KEY ([MigrationId])
);

CREATE TABLE [Hoteles] (
    [Id] int NOT NULL IDENTITY,
    [Nombre] nvarchar(100) NOT NULL,
    [Direccion] nvarchar(200) NOT NULL,
    [Ciudad] nvarchar(60) NOT NULL,
    [Estrellas] int NOT NULL,
    CONSTRAINT [PK_Hoteles] PRIMARY KEY ([Id]),
    CONSTRAINT [CK_Hotel_Estrellas] CHECK (Estrellas BETWEEN 1 AND 5)
);

CREATE TABLE [ServiciosAdicionales] (
    [Id] int NOT NULL IDENTITY,
    [Nombre] nvarchar(80) NOT NULL,
    [Descripcion] nvarchar(200) NULL,
    [Precio] decimal(10,2) NOT NULL,
    CONSTRAINT [PK_ServiciosAdicionales] PRIMARY KEY ([Id])
);

CREATE TABLE [Usuarios] (
    [Id] int NOT NULL IDENTITY,
    [NombreCompleto] nvarchar(100) NOT NULL,
    [Email] nvarchar(100) NOT NULL,
    [Telefono] nvarchar(9) NULL,
    [FechaRegistro] datetime2 NOT NULL DEFAULT (GETDATE()),
    CONSTRAINT [PK_Usuarios] PRIMARY KEY ([Id])
);

CREATE TABLE [Habitaciones] (
    [Id] int NOT NULL IDENTITY,
    [Numero] nvarchar(10) NOT NULL,
    [Tipo] nvarchar(20) NOT NULL,
    [PrecioPorNoche] decimal(10,2) NOT NULL,
    [Capacidad] int NOT NULL,
    [Activa] bit NOT NULL,
    [HotelId] int NOT NULL,
    CONSTRAINT [PK_Habitaciones] PRIMARY KEY ([Id]),
    CONSTRAINT [CK_Habitacion_Precio] CHECK (PrecioPorNoche > 0),
    CONSTRAINT [CK_Habitacion_Tipo] CHECK (Tipo IN ('Simple','Doble','Suite')),
    CONSTRAINT [FK_Habitaciones_Hoteles_HotelId] FOREIGN KEY ([HotelId]) REFERENCES [Hoteles] ([Id]) ON DELETE NO ACTION
);

CREATE TABLE [Reservas] (
    [Id] int NOT NULL IDENTITY,
    [FechaCreacion] datetime2 NOT NULL DEFAULT (GETDATE()),
    [FechaEntrada] date NOT NULL,
    [FechaSalida] date NOT NULL,
    [Estado] nvarchar(20) NOT NULL DEFAULT N'Pendiente',
    [Total] decimal(10,2) NOT NULL,
    [UsuarioId] int NOT NULL,
    CONSTRAINT [PK_Reservas] PRIMARY KEY ([Id]),
    CONSTRAINT [CK_Reserva_Estado] CHECK (Estado IN ('Pendiente','Confirmada','Cancelada')),
    CONSTRAINT [CK_Reserva_Fechas] CHECK (FechaSalida > FechaEntrada),
    CONSTRAINT [FK_Reservas_Usuarios_UsuarioId] FOREIGN KEY ([UsuarioId]) REFERENCES [Usuarios] ([Id]) ON DELETE NO ACTION
);

CREATE TABLE [ReservaDetalles] (
    [Id] int NOT NULL IDENTITY,
    [ReservaId] int NOT NULL,
    [HabitacionId] int NOT NULL,
    [Noches] int NOT NULL,
    [PrecioPorNoche] decimal(10,2) NOT NULL,
    [Subtotal] decimal(10,2) NOT NULL,
    CONSTRAINT [PK_ReservaDetalles] PRIMARY KEY ([Id]),
    CONSTRAINT [FK_ReservaDetalles_Habitaciones_HabitacionId] FOREIGN KEY ([HabitacionId]) REFERENCES [Habitaciones] ([Id]) ON DELETE NO ACTION,
    CONSTRAINT [FK_ReservaDetalles_Reservas_ReservaId] FOREIGN KEY ([ReservaId]) REFERENCES [Reservas] ([Id]) ON DELETE CASCADE
);

CREATE TABLE [ReservaServicios] (
    [Id] int NOT NULL IDENTITY,
    [ReservaId] int NOT NULL,
    [ServicioAdicionalId] int NOT NULL,
    [Cantidad] int NOT NULL,
    [PrecioUnitario] decimal(10,2) NOT NULL,
    [Subtotal] decimal(10,2) NOT NULL,
    CONSTRAINT [PK_ReservaServicios] PRIMARY KEY ([Id]),
    CONSTRAINT [FK_ReservaServicios_Reservas_ReservaId] FOREIGN KEY ([ReservaId]) REFERENCES [Reservas] ([Id]) ON DELETE CASCADE,
    CONSTRAINT [FK_ReservaServicios_ServiciosAdicionales_ServicioAdicionalId] FOREIGN KEY ([ServicioAdicionalId]) REFERENCES [ServiciosAdicionales] ([Id]) ON DELETE NO ACTION
);
GO

-- Indices
CREATE UNIQUE INDEX [IX_Habitaciones_HotelId_Numero] ON [Habitaciones] ([HotelId], [Numero]);
CREATE INDEX [IX_ReservaDetalles_HabitacionId] ON [ReservaDetalles] ([HabitacionId]);
CREATE UNIQUE INDEX [IX_ReservaDetalles_ReservaId_HabitacionId] ON [ReservaDetalles] ([ReservaId], [HabitacionId]);
CREATE INDEX [IX_Reservas_UsuarioId] ON [Reservas] ([UsuarioId]);
CREATE UNIQUE INDEX [IX_ReservaServicios_ReservaId_ServicioAdicionalId] ON [ReservaServicios] ([ReservaId], [ServicioAdicionalId]);
CREATE INDEX [IX_ReservaServicios_ServicioAdicionalId] ON [ReservaServicios] ([ServicioAdicionalId]);
CREATE UNIQUE INDEX [IX_Usuarios_Email] ON [Usuarios] ([Email]);
